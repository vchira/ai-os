//! Bootloader installation for the AiOS installer.
//!
//! Installs GRUB (UEFI or BIOS) into the target system via chroot.
//! All functions require root privileges (run via `sudo`).

/// Install GRUB bootloader on the target system.
///
/// Must be called while the target is mounted at `mount_point`.
/// Bind-mounts `/dev`, `/proc`, `/sys` (and `/sys/firmware/efi/efivars` on UEFI)
/// into the target and runs `grub-install` + `grub-mkconfig` inside a chroot.
///
/// Unbinds all mounts on completion (even on error).
///
/// # Note
/// Requires root — all operations run via `sudo`.
pub fn install_grub(
    mount_point: &str,
    device: &str,
    is_uefi: bool,
    progress: impl Fn(&str),
) -> Result<(), String> {
    progress("Preparing chroot environment...");

    // Bind-mount virtual filesystems needed inside the chroot.
    let mut bind_mounts: Vec<(&str, String)> = vec![
        ("/dev", format!("{mount_point}/dev")),
        ("/proc", format!("{mount_point}/proc")),
        ("/sys", format!("{mount_point}/sys")),
    ];

    if is_uefi {
        bind_mounts.push((
            "/sys/firmware/efi/efivars",
            format!("{mount_point}/sys/firmware/efi/efivars"),
        ));
    }

    for (src, dst) in &bind_mounts {
        super::sudo_mkdir(dst).ok();
        let output = std::process::Command::new("sudo")
            .args(["mount", "--bind", src, dst])
            .output()
            .map_err(|e| format!("Failed to bind-mount {src} -> {dst}: {e}"))?;

        if !output.status.success() {
            let stderr = String::from_utf8_lossy(&output.stderr);
            // Attempt to clean up anything we already mounted.
            unbind_mounts(mount_point, is_uefi);
            return Err(format!("Bind-mount {src} -> {dst} failed: {stderr}"));
        }
    }

    // Run grub-install inside the chroot.
    let grub_result = if is_uefi {
        install_grub_uefi(mount_point, device, &progress)
    } else {
        install_grub_bios(mount_point, device, &progress)
    };

    // Write /etc/default/grub and theme before generating config.
    if grub_result.is_ok() {
        progress("Configuring GRUB theme...");
        write_grub_defaults(mount_point)?;
        write_grub_theme(mount_point)?;

        progress("Generating GRUB configuration...");
        let output = std::process::Command::new("sudo")
            .args(["chroot", mount_point, "grub-mkconfig", "-o", "/boot/grub/grub.cfg"])
            .output()
            .map_err(|e| format!("grub-mkconfig failed to start: {e}"))?;

        if !output.status.success() {
            let stderr = String::from_utf8_lossy(&output.stderr);
            unbind_mounts(mount_point, is_uefi);
            return Err(format!("grub-mkconfig failed: {stderr}"));
        }
    }

    // Always clean up bind mounts.
    unbind_mounts(mount_point, is_uefi);

    grub_result?;

    progress("Bootloader installed");
    Ok(())
}

/// Install GRUB for UEFI systems.
fn install_grub_uefi(mount_point: &str, _device: &str, progress: &dyn Fn(&str)) -> Result<(), String> {
    progress("Installing GRUB (UEFI)...");

    let output = std::process::Command::new("sudo")
        .args([
            "chroot", mount_point,
            "grub-install",
            "--target=x86_64-efi",
            "--efi-directory=/boot/efi",
            "--bootloader-id=AiOS",
            "--recheck",
        ])
        .output()
        .map_err(|e| format!("grub-install (UEFI) failed to start: {e}"))?;

    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        return Err(format!("grub-install (UEFI) failed: {stderr}"));
    }

    Ok(())
}

/// Install GRUB for BIOS/legacy systems.
fn install_grub_bios(mount_point: &str, device: &str, progress: &dyn Fn(&str)) -> Result<(), String> {
    progress("Installing GRUB (BIOS)...");

    let output = std::process::Command::new("sudo")
        .args([
            "chroot", mount_point,
            "grub-install",
            "--target=i386-pc",
            "--recheck",
            device,
        ])
        .output()
        .map_err(|e| format!("grub-install (BIOS) failed to start: {e}"))?;

    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        return Err(format!("grub-install (BIOS) failed: {stderr}"));
    }

    Ok(())
}

/// Write `/etc/default/grub` with AiOS-branded settings.
///
/// Settings:
/// - Hidden 3-second timeout (press Shift/Esc to reveal the menu)
/// - Graphics terminal with dark theme
/// - Quiet boot (no verbose kernel messages)
/// - "AiOS" as the distributor name for the menu entry
fn write_grub_defaults(mount_point: &str) -> Result<(), String> {
    let content = "\
# /etc/default/grub — generated by AiOS installer

# Distributor name (appears in menu entry: \"AiOS GNU/Linux\")
GRUB_DISTRIBUTOR=\"AiOS\"

# Boot the default entry after 3 seconds
GRUB_TIMEOUT=3

# Hidden menu — press Shift (BIOS) or Esc (UEFI) to reveal
GRUB_TIMEOUT_STYLE=hidden

# Quiet boot: no verbose kernel messages, show splash
GRUB_CMDLINE_LINUX_DEFAULT=\"quiet splash loglevel=3\"
GRUB_CMDLINE_LINUX=\"\"

# Use graphical terminal with auto-detected resolution
GRUB_TERMINAL_OUTPUT=gfxterm
GRUB_GFXMODE=auto
GRUB_GFXPAYLOAD_LINUX=keep

# Load the AiOS GRUB theme
GRUB_THEME=/boot/grub/themes/aios/theme.txt

# Disable OS prober (single-OS system)
GRUB_DISABLE_OS_PROBER=true
";

    let grub_defaults_path = format!("{mount_point}/etc/default/grub");
    super::sudo_write(&grub_defaults_path, content)
}

/// Write a minimal GRUB theme for a clean dark boot screen.
///
/// Creates `/boot/grub/themes/aios/theme.txt` with dark background,
/// clean font, and a single-entry styled menu. This is referenced by
/// `GRUB_THEME` in `/etc/default/grub`.
fn write_grub_theme(mount_point: &str) -> Result<(), String> {
    let theme_dir = format!("{mount_point}/boot/grub/themes/aios");
    super::sudo_mkdir(&theme_dir)?;

    let theme = "\
# AiOS GRUB Theme — minimal dark boot screen

# Dark background
desktop-color: \"#0a0a0a\"

# Title text (top of screen)
title-text: \"AiOS\"
title-font: \"DejaVu Sans Bold 16\"
title-color: \"#c0c0c0\"

# Menu appearance
+ boot_menu {
    left = 25%
    top = 40%
    width = 50%
    height = 30%
    item_font = \"DejaVu Sans 14\"
    item_color = \"#a0a0a0\"
    selected_item_font = \"DejaVu Sans Bold 14\"
    selected_item_color = \"#ffffff\"
    item_height = 28
    item_padding = 8
    item_spacing = 4
    selected_item_pixmap_style = \"highlight_*\"
}

# Progress bar (timeout countdown)
+ progress_bar {
    id = \"__timeout__\"
    left = 25%
    top = 75%
    width = 50%
    height = 6
    show_text = false
    fg_color = \"#404040\"
    bg_color = \"#1a1a1a\"
    border_color = \"#2a2a2a\"
    text_color = \"#808080\"
}

# Bottom label
+ label {
    left = 0
    top = 92%
    width = 100%
    align = \"center\"
    color = \"#505050\"
    font = \"DejaVu Sans 10\"
    text = \"Press Esc for boot menu\"
}
";

    let theme_path = format!("{theme_dir}/theme.txt");
    super::sudo_write(&theme_path, theme)
}

/// Unmount bind mounts in reverse order. Best-effort — ignores errors.
fn unbind_mounts(mount_point: &str, is_uefi: bool) {
    // Reverse order of mounting.
    let mut paths = Vec::new();

    if is_uefi {
        paths.push(format!("{mount_point}/sys/firmware/efi/efivars"));
    }
    paths.push(format!("{mount_point}/sys"));
    paths.push(format!("{mount_point}/proc"));
    paths.push(format!("{mount_point}/dev"));

    for path in &paths {
        let _ = std::process::Command::new("sudo")
            .args(["umount", path])
            .output();
    }
}


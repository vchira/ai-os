static int active_theme = THEME_DARK;

const ui_theme_t *theme_get(void) {
    return &themes[active_theme];
}

void theme_set(int id) {
    if (id >= 0 && id < THEME_COUNT)
        active_theme = id;
}

const char *theme_name(int id) {
    if (id >= 0 && id < THEME_COUNT)
        return themes[id].name;
    return "?";
}

int theme_count(void) {
    return THEME_COUNT;
}

int theme_current_id(void) {
    return active_theme;
}
